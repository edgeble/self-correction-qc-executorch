#!/bin/bash
# ExecuTorch 1.5.1 runtime + Qualcomm backend for Linux aarch64 (Ubuntu 24.04 boards),
# cross-compiled with gcc-aarch64-linux-gnu inside executorch-x86:1.5.1-cross.
set -e
SRC=/work/et/executorch; B=/work/build-et-aarch64; I=/work/et-aarch64
COMMON="-DCMAKE_BUILD_TYPE=Release -DCMAKE_C_COMPILER=aarch64-linux-gnu-gcc -DCMAKE_CXX_COMPILER=aarch64-linux-gnu-g++ -DCMAKE_SYSTEM_NAME=Linux -DCMAKE_SYSTEM_PROCESSOR=aarch64 -DQNN_SDK_ROOT=/qairt -DPYTHON_EXECUTABLE=python3"
cmake -S $SRC -B $B -G Ninja -DCMAKE_INSTALL_PREFIX=$I $COMMON \
  -DEXECUTORCH_BUILD_QNN=ON -DEXECUTORCH_BUILD_XNNPACK=OFF \
  -DEXECUTORCH_BUILD_EXTENSION_MODULE=ON -DEXECUTORCH_BUILD_EXTENSION_DATA_LOADER=ON \
  -DEXECUTORCH_BUILD_EXTENSION_FLAT_TENSOR=ON -DEXECUTORCH_BUILD_EXTENSION_NAMED_DATA_MAP=ON \
  -DEXECUTORCH_BUILD_EXTENSION_TENSOR=ON -DEXECUTORCH_BUILD_KERNELS_QUANTIZED=ON \
  -DEXECUTORCH_BUILD_KERNELS_OPTIMIZED=ON -DEXECUTORCH_BUILD_DEVTOOLS=ON \
  -DEXECUTORCH_ENABLE_EVENT_TRACER=ON -DEXECUTORCH_ENABLE_LOGGING=ON \
  -DEXECUTORCH_BUILD_EXECUTOR_RUNNER=OFF -DFLATCC_ALLOW_WERROR=OFF
cmake --build $B -j$(nproc) --target install
cmake -S $SRC/examples/qualcomm -B $B/examples -G Ninja -DCMAKE_PREFIX_PATH=$I $COMMON
cmake --build $B/examples -j$(nproc)
echo BUILD-OK
